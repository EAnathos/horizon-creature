//! Writes the library's table of the series' recipes, `common/native/api/src/recipes.rs`, for the creature guide's
//! Items tab (common/SPECS.md §7.2): how each item is made, and what it is used to make.
//!
//! Read from every module's `content/data/<id>/recipe/**/*.json`: shaped and shapeless crafting, smelting, smoking,
//! campfire cooking and brewing. Each slot holds the items that fit it (a tag's items: the series' own tags read from
//! the modules, Minecraft's from `VANILLA_TAGS`), the first one drawn. Written by `cargo creature tab` with the
//! creative tab, checked by `cargo creature check`.
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::modules;

const OUT: &str = "common/native/api/src/recipes.rs";

/// The items drawn for Minecraft's tags the series' recipes use (the game's own lists are in its jar).
const VANILLA_TAGS: &[(&str, &[&str])] = &[
    ("minecraft:logs", &["minecraft:oak_log"]),
    ("minecraft:planks", &["minecraft:oak_planks"]),
    ("minecraft:wool", &["minecraft:white_wool"]),
    ("minecraft:wooden_slabs", &["minecraft:oak_slab"]),
];

/// One recipe, as the library's `Recipe`.
#[derive(Debug, PartialEq)]
struct Recipe {
    station: &'static str,
    grid: [Vec<String>; 9],
    result: String,
    count: u64,
}

pub fn run() -> crate::Result {
    let (out, text, count) = render()?;
    std::fs::write(&out, text).map_err(|e| format!("{}: {e}", out.display()))?;
    println!("{}: {count} recipes", out.display());
    Ok(())
}

/// The table's path, its content and its number of recipes, without writing it.
pub fn render() -> crate::Result<(PathBuf, String, usize)> {
    let all: Vec<_> = std::iter::once(modules::library()?).chain(modules::mods()?).collect();
    // The series' item tags, by id (`creature:feathers`): their items.
    let mut tags: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut files = Vec::new();
    for m in &all {
        let Some(content) = m.content() else {
            continue;
        };
        let data = content.join("data");
        for ns in read_dir(&data) {
            let Some(name) = ns.file_name().and_then(|n| n.to_str()).map(str::to_owned) else {
                continue;
            };
            for tag in json_files(&ns.join("tags/item")) {
                let id = format!("{name}:{}", tag_name(&ns.join("tags/item"), &tag));
                let json = read_json(&tag)?;
                let items = json["values"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .filter_map(|v| v.as_str().or_else(|| v["id"].as_str()).map(str::to_owned))
                    .collect();
                tags.insert(id, items);
            }
            files.extend(json_files(&ns.join("recipe")));
        }
    }
    files.sort();
    let mut recipes = Vec::new();
    for file in &files {
        let json = read_json(file)?;
        if let Some(r) = recipe(&json, &tags).map_err(|e| format!("{}: {e}", rel(file)))? {
            recipes.push(r);
        }
    }
    let mut rust = String::from(
        "// Generated by `cargo creature tab` from every module's recipes: do not edit.\n\
         use crate::items::{Recipe, Station};\n\n\
         #[rustfmt::skip]\n\
         pub static RECIPES: &[Recipe] = &[\n",
    );
    for r in &recipes {
        let grid: Vec<String> = r
            .grid
            .iter()
            .map(|slot| {
                format!(
                    "&[{}]",
                    slot.iter().map(|i| format!("{i:?}")).collect::<Vec<_>>().join(", ")
                )
            })
            .collect();
        writeln!(
            rust,
            "    Recipe {{ station: Station::{}, grid: [{}], result: {:?}, count: {} }},",
            r.station,
            grid.join(", "),
            r.result,
            r.count
        )
        .unwrap();
    }
    rust.push_str("];\n");
    Ok((crate::root().join(OUT), rust, recipes.len()))
}

/// A recipe file's recipe; none for a type the book doesn't draw.
fn recipe(json: &Value, tags: &BTreeMap<String, Vec<String>>) -> crate::Result<Option<Recipe>> {
    let kind = json["type"].as_str().unwrap_or("");
    let station = match kind {
        "minecraft:crafting_shaped" | "minecraft:crafting_shapeless" => "Crafting",
        "minecraft:smelting" => "Furnace",
        "minecraft:smoking" => "Smoker",
        "minecraft:campfire_cooking" => "Campfire",
        "minecraft:brewing" => "Brewing",
        _ => return Ok(None),
    };
    let mut grid: [Vec<String>; 9] = Default::default();
    match kind {
        "minecraft:crafting_shaped" => {
            let pattern: Vec<&str> = json["pattern"]
                .as_array()
                .into_iter()
                .flatten()
                .filter_map(Value::as_str)
                .collect();
            for (row, line) in pattern.iter().enumerate().take(3) {
                for (col, symbol) in line.chars().enumerate().take(3) {
                    if symbol != ' ' {
                        let key = &json["key"][symbol.to_string()];
                        grid[row * 3 + col] = ingredient(key, tags)?;
                    }
                }
            }
        }
        "minecraft:crafting_shapeless" => {
            for (k, item) in json["ingredients"].as_array().into_iter().flatten().take(9).enumerate() {
                grid[k] = ingredient(item, tags)?;
            }
        }
        "minecraft:brewing" => {
            grid[1] = ingredient(&json["reagent"], tags)?;
            grid[7] = ingredient(&json["input"], tags)?;
        }
        _ => grid[4] = ingredient(&json["ingredient"], tags)?,
    }
    let result = if kind == "minecraft:brewing" {
        &json["output"]
    } else {
        &json["result"]
    };
    let id = result.as_str().or_else(|| result["id"].as_str()).ok_or("no result")?;
    Ok(Some(Recipe {
        station,
        grid,
        result: id.to_owned(),
        count: result["count"].as_u64().unwrap_or(1),
    }))
}

/// The items an ingredient takes: an item id, `#tag`, `{"item": ...}`, `{"tag": ...}` or a list of them.
fn ingredient(v: &Value, tags: &BTreeMap<String, Vec<String>>) -> crate::Result<Vec<String>> {
    let tag = |name: &str| -> crate::Result<Vec<String>> {
        if let Some(items) = tags.get(name) {
            return Ok(items.clone());
        }
        VANILLA_TAGS
            .iter()
            .find(|(t, _)| *t == name)
            .map(|(_, items)| items.iter().map(|i| (*i).to_owned()).collect())
            .ok_or(format!(
                "tag #{name}: add the item to draw for it in tools/src/recipes.rs"
            ))
    };
    match v {
        Value::String(s) => match s.strip_prefix('#') {
            Some(t) => tag(t),
            None => Ok(vec![s.clone()]),
        },
        Value::Array(list) => {
            let mut items = Vec::new();
            for i in list {
                items.extend(ingredient(i, tags)?);
            }
            Ok(items)
        }
        Value::Object(_) => match (v["item"].as_str(), v["tag"].as_str()) {
            (Some(item), _) => Ok(vec![item.to_owned()]),
            (None, Some(t)) => tag(t),
            _ => Err("an ingredient with no item".into()),
        },
        _ => Ok(Vec::new()),
    }
}

fn read_dir(dir: &Path) -> Vec<PathBuf> {
    let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .filter_map(|e| e.ok().map(|e| e.path()))
        .collect();
    entries.sort();
    entries
}

/// Every `.json` file under `dir`, at any depth.
fn json_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for path in read_dir(dir) {
        if path.is_dir() {
            out.extend(json_files(&path));
        } else if path.extension().is_some_and(|e| e == "json") {
            out.push(path);
        }
    }
    out
}

/// `tags/item/feathers.json` → `feathers`.
fn tag_name(root: &Path, file: &Path) -> String {
    let rel = file.strip_prefix(root).unwrap_or(file).with_extension("");
    rel.to_string_lossy().replace('\\', "/")
}

fn read_json(path: &Path) -> crate::Result<Value> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", rel(path)))?;
    serde_json::from_str(&text).map_err(|e| format!("{}: {e}", rel(path)))
}

fn rel(path: &Path) -> String {
    path.strip_prefix(crate::root()).unwrap_or(path).display().to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn lays_out_a_shaped_recipe_with_a_tag() {
        let tags = BTreeMap::from([(
            "creature:feathers".to_owned(),
            vec!["minecraft:feather".to_owned(), "vulture:feather".to_owned()],
        )]);
        let r = recipe(
            &json!({"type": "minecraft:crafting_shaped", "pattern": ["X", "#"],
                "key": {"X": "minecraft:flint", "#": "#creature:feathers"}, "result": {"id": "minecraft:arrow", "count": 4}}),
            &tags,
        )
        .unwrap()
        .unwrap();
        assert_eq!(r.station, "Crafting");
        assert_eq!(r.grid[0], vec!["minecraft:flint"]);
        assert_eq!(r.grid[3], vec!["minecraft:feather", "vulture:feather"]);
        assert!(r.grid[1].is_empty());
        assert_eq!((r.result.as_str(), r.count), ("minecraft:arrow", 4));
    }

    #[test]
    fn puts_brewing_and_smelting_where_their_stations_show_them() {
        let none = BTreeMap::new();
        let brew = recipe(
            &json!({"type": "minecraft:brewing", "input": {"item": "minecraft:potion"},
                "reagent": {"item": "fairies:fairy_dust"}, "output": {"id": "minecraft:potion"}}),
            &none,
        )
        .unwrap()
        .unwrap();
        assert_eq!(
            (brew.grid[1][0].as_str(), brew.grid[7][0].as_str()),
            ("fairies:fairy_dust", "minecraft:potion")
        );
        let smelt = recipe(
            &json!({"type": "minecraft:smelting", "ingredient": "vulture:raw_vulture", "result": {"id": "vulture:cooked_vulture"}}),
            &none,
        )
        .unwrap()
        .unwrap();
        assert_eq!(
            (smelt.station, smelt.grid[4][0].as_str()),
            ("Furnace", "vulture:raw_vulture")
        );
        assert!(
            recipe(&json!({"type": "minecraft:stonecutting"}), &none)
                .unwrap()
                .is_none()
        );
    }
}
