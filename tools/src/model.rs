//! Converts a mod's Blockbench model into Rust data (common/SPECS.md §3.1).
//!
//! Reads `mods/<mod>/assets/models/<model>.bbmodel` ("free" format, box UV) and writes the mod's
//! `native/api/src/model.rs` (the model named after the mod) or `model_<model>.rs` (another one): the group tree (pivots
//! in texels, rotations in degrees) and their cubes, with each face's UVs in `Host::draw_cube`'s order (down, up,
//! north, south, west, east), in texels of 16 per side like a block model, as the library's `creature::model::Part`.
//! The library draws these cubes with the mod's texture (`content/assets/<mod>/textures/entity/...`).
use std::collections::HashMap;
use std::fmt::Write as _;

use serde_json::Value;

const FACES: [&str; 6] = ["down", "up", "north", "south", "west", "east"];

pub fn run(module: &str, name: Option<&str>) -> crate::Result {
    let m = crate::modules::find(module)?;
    let name = name.unwrap_or(&m.id);
    let src = m.dir.join(format!("assets/models/{name}.bbmodel"));
    let file = if name == m.id {
        "model.rs".to_owned()
    } else {
        format!("model_{name}.rs")
    };
    let out = m.dir.join("native/api/src").join(file);
    let text = std::fs::read_to_string(&src).map_err(|e| format!("{}: {e}", src.display()))?;
    let model: Value = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", src.display()))?;
    let source = src.strip_prefix(crate::root()).unwrap_or(&src).display().to_string();
    // The command that remakes it: the model's name is left out when it is the mod's.
    let args = if name == m.id {
        module.to_owned()
    } else {
        format!("{module} {name}")
    };
    let rust = convert(&model, &args, &source, name)?;
    std::fs::write(&out, rust).map_err(|e| format!("{}: {e}", out.display()))?;
    let count = |key: &str| model[key].as_array().map_or(0, Vec::len);
    println!(
        "{}: {} cubes, {} groups",
        out.display(),
        count("elements"),
        count("groups")
    );
    Ok(())
}

/// The whole `model.rs` for a parsed `.bbmodel`: `pub static <NAME>: Part`. `args` and `source` go in its header.
fn convert(model: &Value, args: &str, source: &str, name: &str) -> crate::Result<String> {
    let scale = |key: &str| 16.0 / model["resolution"][key].as_f64().unwrap_or(16.0);
    let scale = (scale("width"), scale("height"));
    let by_uuid = |key: &str| -> HashMap<&str, &Value> {
        model[key]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(|v| Some((v["uuid"].as_str()?, v)))
            .collect()
    };
    let tree = Tree {
        elements: by_uuid("elements"),
        groups: by_uuid("groups"),
        scale,
    };
    let roots: Vec<&Value> = model["outliner"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|n| n.is_object())
        .collect();
    let [root] = roots[..] else {
        return Err("the model must have a single root group".into());
    };
    let mut out = format!(
        "// Generated by `cargo creature model {args}` from {source}: do not edit.\nuse creature::model::{{Cube, Part}};\n\n"
    );
    let _ = writeln!(
        out,
        "#[rustfmt::skip]\npub static {}: Part = {};",
        name.to_uppercase(),
        tree.part(root, 0)?
    );
    Ok(out)
}

struct Tree<'a> {
    elements: HashMap<&'a str, &'a Value>,
    groups: HashMap<&'a str, &'a Value>,
    scale: (f64, f64),
}

impl Tree<'_> {
    fn cube(&self, e: &Value) -> crate::Result<String> {
        let name = e["name"].as_str().unwrap_or("");
        if e.get("rotation").is_some_and(|r| vector(r).iter().any(|&v| v != 0.0)) {
            return Err(format!("cube {name} is rotated: rotate its group instead"));
        }
        let mut uvs = Vec::new();
        for face in FACES {
            let uv = vector(&e["faces"][face]["uv"]);
            let [u0, v0, u1, v1] = uv[..] else {
                return Err(format!("cube {name} has no {face} UV"));
            };
            let (su, sv) = self.scale;
            uvs.push(list(&[u0 * su, v0 * sv, u1 * su, v1 * sv]));
        }
        Ok(format!(
            "Cube {{ name: {name:?}, from: {}, to: {}, uv: [{}] }}",
            list(&vector(&e["from"])),
            list(&vector(&e["to"])),
            uvs.join(", ")
        ))
    }

    fn part(&self, node: &Value, depth: usize) -> crate::Result<String> {
        let uuid = node["uuid"].as_str().unwrap_or("");
        let g = self.groups.get(uuid).ok_or_else(|| format!("no group {uuid}"))?;
        let pad = "    ".repeat(depth + 1);
        let mut cubes = String::new();
        let mut children = String::new();
        for child in node["children"].as_array().into_iter().flatten() {
            if let Some(id) = child.as_str() {
                let e = self.elements.get(id).ok_or_else(|| format!("no element {id}"))?;
                if e["export"].as_bool() != Some(false) {
                    let _ = write!(cubes, "\n{pad}    {},", self.cube(e)?);
                }
            } else {
                let _ = write!(children, "\n{pad}    {},", self.part(child, depth + 1)?);
            }
        }
        let rotation = g.get("rotation").map_or(vec![0.0; 3], vector);
        Ok(format!(
            "Part {{\n{pad}name: {:?},\n{pad}pivot: {},\n{pad}rotation: {},\n{pad}cubes: &[{cubes}\n{pad}],\n\
             {pad}children: &[{children}\n{pad}],\n{}}}",
            g["name"].as_str().unwrap_or(""),
            list(&vector(&g["origin"])),
            list(&rotation),
            &pad[4..],
        ))
    }
}

fn vector(v: &Value) -> Vec<f64> {
    v.as_array().into_iter().flatten().filter_map(Value::as_f64).collect()
}

/// `[1.0, 0.25]`: `{:?}` keeps a `.0` on whole numbers, so every value is an `f32` literal.
fn list(values: &[f64]) -> String {
    let items: Vec<String> = values.iter().map(|v| format!("{v:?}")).collect();
    format!("[{}]", items.join(", "))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn converts_a_group_with_one_cube() {
        let model = serde_json::json!({
            "resolution": {"width": 64, "height": 64},
            "elements": [{"uuid": "c", "name": "body", "from": [-5, 9, -7], "to": [5, 18, 8],
                "faces": {"down": {"uv": [35, 0, 25, 15]}, "up": {"uv": [25, 15, 15, 0]},
                    "north": {"uv": [15, 15, 25, 24]}, "south": {"uv": [40, 15, 50, 24]},
                    "west": {"uv": [25, 15, 40, 24]}, "east": {"uv": [0, 15, 15, 24]}}}],
            "groups": [{"uuid": "g", "name": "vulture", "origin": [0, 0, 0], "rotation": [0, 0, 0]}],
            "outliner": [{"uuid": "g", "children": ["c"]}]
        });
        let rust = convert(&model, "vulture", "vulture.bbmodel", "vulture").unwrap();
        assert!(rust.contains("name: \"vulture\""), "{rust}");
        assert!(rust.contains("from: [-5.0, 9.0, -7.0]"), "{rust}");
        assert!(rust.contains("[8.75, 0.0, 6.25, 3.75]"), "{rust}");
    }

    #[test]
    fn refuses_a_rotated_cube() {
        let model = serde_json::json!({
            "resolution": {"width": 64, "height": 64},
            "elements": [{"uuid": "c", "name": "beak", "from": [0, 0, 0], "to": [1, 1, 1], "rotation": [0, 22.5, 0],
                "faces": {}}],
            "groups": [{"uuid": "g", "name": "vulture", "origin": [0, 0, 0]}],
            "outliner": [{"uuid": "g", "children": ["c"]}]
        });
        assert!(
            convert(&model, "vulture", "vulture.bbmodel", "vulture")
                .unwrap_err()
                .contains("rotate its group")
        );
    }
}
