//! Pictures of every mod's Blockbench models for the docs (`docs/MODELS.md`).
//!
//! `cargo creature preview` reads each module's `assets/models/*.bbmodel` (box UV, cubes not rotated, as
//! `cargo creature model` needs them) with its embedded texture, draws it from the front and from the back (three
//! quarters, a little from above, without perspective) into `docs/models/<mod>-<model>-{front,back}.png`, and writes
//! `docs/MODELS.md`, which shows them. The models are drawn as built in Blockbench, at rest: the game poses them.
use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

/// The pictures' size, in pixels, and the margin left around the model.
const SIZE: (usize, usize) = (480, 360);
const MARGIN: f64 = 16.0;
/// The two views: turned this much around the vertical (degrees; 0 faces the model's front, +z), and seen from this
/// far above.
const VIEWS: [(&str, f64); 2] = [("front", 35.0), ("back", 215.0)];
const PITCH: f64 = 25.0;

/// A cube face: the light it gets, and its corners for the UV's (u0, v0), (u1, v0), (u1, v1), (u0, v1), each corner
/// picking the low (false) or high (true) side of x, y and z.
const FACES: [(&str, f64, [[bool; 3]; 4]); 6] = [
    (
        "north",
        0.8,
        [
            [true, true, false],
            [false, true, false],
            [false, false, false],
            [true, false, false],
        ],
    ),
    (
        "south",
        0.8,
        [
            [false, true, true],
            [true, true, true],
            [true, false, true],
            [false, false, true],
        ],
    ),
    (
        "east",
        0.6,
        [
            [true, true, true],
            [true, true, false],
            [true, false, false],
            [true, false, true],
        ],
    ),
    (
        "west",
        0.6,
        [
            [false, true, false],
            [false, true, true],
            [false, false, true],
            [false, false, false],
        ],
    ),
    (
        "up",
        1.0,
        [
            [false, true, false],
            [true, true, false],
            [true, true, true],
            [false, true, true],
        ],
    ),
    (
        "down",
        0.5,
        [
            [false, false, true],
            [true, false, true],
            [true, false, false],
            [false, false, false],
        ],
    ),
];

struct Texture {
    width: usize,
    height: usize,
    rgba: Vec<u8>,
}

/// One face to draw: its corners in model space, their UVs in texture pixels, its light.
struct Quad {
    corners: [[f64; 3]; 4],
    uv: [[f64; 2]; 4],
    light: f64,
}

pub fn run() -> crate::Result {
    let root = crate::root();
    let out = root.join("docs/models");
    std::fs::create_dir_all(&out).map_err(|e| format!("{}: {e}", out.display()))?;
    let mut doc = String::from(
        "# Models\n\nThe Blockbench models of each mod, as built (at rest; the game poses them). Generated by \
         `cargo creature preview` from `mods/<mod>/assets/models/*.bbmodel`: run it again after changing a model.\n",
    );
    for m in std::iter::once(crate::modules::library()?).chain(crate::modules::mods()?) {
        let dir = m.dir.join("assets/models");
        let Ok(read) = std::fs::read_dir(&dir) else {
            continue;
        };
        let mut models: Vec<_> = read
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "bbmodel"))
            .collect();
        if models.is_empty() {
            continue;
        }
        models.sort();
        let _ = write!(doc, "\n## {}\n", m.id);
        for path in models {
            let name = path.file_stem().and_then(|s| s.to_str()).unwrap_or("model").to_owned();
            let (cubes, texture) = picture(&path, &out, &m.id, &name)?;
            let source = path.strip_prefix(&root).unwrap_or(&path).display().to_string();
            let _ = write!(
                doc,
                "\n### {name}\n\n`{source}`: {cubes} cubes, texture {}×{}.\n\n\
                 ![{name}, front](models/{id}-{name}-front.png) ![{name}, back](models/{id}-{name}-back.png)\n",
                texture.0,
                texture.1,
                id = m.id,
            );
            println!("{}: {cubes} cubes", source);
        }
    }
    let file = root.join("docs/MODELS.md");
    std::fs::write(&file, doc).map_err(|e| format!("{}: {e}", file.display()))?;
    println!("{}", file.display());
    Ok(())
}

/// Draws one model's two views. Its cube count and texture size.
fn picture(path: &Path, out: &Path, module: &str, name: &str) -> crate::Result<(usize, (usize, usize))> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let model: Value = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    let texture = texture(&model).map_err(|e| format!("{}: {e}", path.display()))?;
    // UVs are in the project's resolution; the texture may be bigger.
    let res = |key: &str, size: usize| size as f64 / model["resolution"][key].as_f64().unwrap_or(size as f64);
    let (su, sv) = (res("width", texture.width), res("height", texture.height));
    let quads: Vec<Quad> = model["elements"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|e| e["type"].as_str().unwrap_or("cube") == "cube" && e["export"].as_bool() != Some(false))
        .flat_map(|e| cube(e, su, sv))
        .collect();
    let cubes = quads.len() / 6;
    for (view, yaw) in VIEWS {
        let image = draw(&quads, &texture, yaw);
        let file = out.join(format!("{module}-{name}-{view}.png"));
        write_png(&file, &image)?;
    }
    Ok((cubes, (texture.width, texture.height)))
}

fn vector(v: &Value) -> Vec<f64> {
    v.as_array().into_iter().flatten().filter_map(Value::as_f64).collect()
}

fn cube(e: &Value, su: f64, sv: f64) -> Vec<Quad> {
    let (from, to) = (vector(&e["from"]), vector(&e["to"]));
    if from.len() != 3 || to.len() != 3 {
        return Vec::new();
    }
    let inflate = e["inflate"].as_f64().unwrap_or(0.0);
    let side = |k: usize, high: bool| if high { to[k] + inflate } else { from[k] - inflate };
    FACES
        .iter()
        .filter_map(|(face, light, corners)| {
            let uv = vector(&e["faces"][*face]["uv"]);
            let [u0, v0, u1, v1] = uv[..] else {
                return None;
            };
            let corner = |c: [bool; 3]| [side(0, c[0]), side(1, c[1]), side(2, c[2])];
            Some(Quad {
                corners: corners.map(corner),
                uv: [
                    [u0 * su, v0 * sv],
                    [u1 * su, v0 * sv],
                    [u1 * su, v1 * sv],
                    [u0 * su, v1 * sv],
                ],
                light: *light,
            })
        })
        .collect()
}

/// The point as seen from the view: x right, y up, z towards the viewer.
fn view(p: [f64; 3], yaw: f64) -> [f64; 3] {
    let (sy, cy) = yaw.to_radians().sin_cos();
    let (sp, cp) = PITCH.to_radians().sin_cos();
    let (x, z) = (p[0] * cy + p[2] * sy, -p[0] * sy + p[2] * cy);
    [x, p[1] * cp - z * sp, p[1] * sp + z * cp]
}

/// Draws the quads (nearest texel, alpha cut at half, depth tested) into an RGBA picture, fitted to its size.
fn draw(quads: &[Quad], texture: &Texture, yaw: f64) -> Vec<u8> {
    let (w, h) = SIZE;
    let seen: Vec<[[f64; 3]; 4]> = quads.iter().map(|q| q.corners.map(|c| view(c, yaw))).collect();
    let (mut lo, mut hi) = ([f64::MAX; 2], [f64::MIN; 2]);
    for p in seen.iter().flatten() {
        for k in 0..2 {
            lo[k] = lo[k].min(p[k]);
            hi[k] = hi[k].max(p[k]);
        }
    }
    let scale = ((w as f64 - 2.0 * MARGIN) / (hi[0] - lo[0])).min((h as f64 - 2.0 * MARGIN) / (hi[1] - lo[1]));
    let offset = [
        (w as f64 - (hi[0] - lo[0]) * scale) / 2.0,
        (h as f64 - (hi[1] - lo[1]) * scale) / 2.0,
    ];
    let screen = |p: [f64; 3]| {
        [
            (p[0] - lo[0]) * scale + offset[0],
            (hi[1] - p[1]) * scale + offset[1],
            p[2],
        ]
    };
    let mut rgba = vec![0u8; w * h * 4];
    let mut depth = vec![f64::MIN; w * h];
    for (q, corners) in quads.iter().zip(&seen) {
        let s = corners.map(screen);
        for [a, b, c] in [[0, 1, 2], [0, 2, 3]] {
            triangle(
                [s[a], s[b], s[c]],
                [q.uv[a], q.uv[b], q.uv[c]],
                q.light,
                texture,
                &mut rgba,
                &mut depth,
            );
        }
    }
    rgba
}

fn triangle(p: [[f64; 3]; 3], uv: [[f64; 2]; 3], light: f64, texture: &Texture, rgba: &mut [u8], depth: &mut [f64]) {
    let (w, h) = SIZE;
    let area = (p[1][0] - p[0][0]) * (p[2][1] - p[0][1]) - (p[2][0] - p[0][0]) * (p[1][1] - p[0][1]);
    if area.abs() < 1e-9 {
        return;
    }
    let x0 = p.iter().map(|q| q[0]).fold(f64::MAX, f64::min).floor().max(0.0) as usize;
    let x1 = p
        .iter()
        .map(|q| q[0])
        .fold(f64::MIN, f64::max)
        .ceil()
        .min(w as f64 - 1.0) as usize;
    let y0 = p.iter().map(|q| q[1]).fold(f64::MAX, f64::min).floor().max(0.0) as usize;
    let y1 = p
        .iter()
        .map(|q| q[1])
        .fold(f64::MIN, f64::max)
        .ceil()
        .min(h as f64 - 1.0) as usize;
    for y in y0..=y1 {
        for x in x0..=x1 {
            let (px, py) = (x as f64 + 0.5, y as f64 + 0.5);
            let edge = |a: [f64; 3], b: [f64; 3]| (b[0] - a[0]) * (py - a[1]) - (px - a[0]) * (b[1] - a[1]);
            let l = [
                edge(p[1], p[2]) / area,
                edge(p[2], p[0]) / area,
                edge(p[0], p[1]) / area,
            ];
            if l.iter().any(|&v| v < 0.0) {
                continue;
            }
            let z = l[0] * p[0][2] + l[1] * p[1][2] + l[2] * p[2][2];
            let i = y * w + x;
            if z <= depth[i] {
                continue;
            }
            let u = l[0] * uv[0][0] + l[1] * uv[1][0] + l[2] * uv[2][0];
            let v = l[0] * uv[0][1] + l[1] * uv[1][1] + l[2] * uv[2][1];
            let tx = (u.floor().max(0.0) as usize).min(texture.width - 1);
            let ty = (v.floor().max(0.0) as usize).min(texture.height - 1);
            let t = &texture.rgba[(ty * texture.width + tx) * 4..][..4];
            if t[3] < 128 {
                continue;
            }
            depth[i] = z;
            for k in 0..3 {
                rgba[i * 4 + k] = (f64::from(t[k]) * light).round() as u8;
            }
            rgba[i * 4 + 3] = 255;
        }
    }
}

/// The model's first texture, embedded in it as a PNG data URI.
fn texture(model: &Value) -> Result<Texture, String> {
    let source = model["textures"][0]["source"].as_str().ok_or("no embedded texture")?;
    let data = source
        .strip_prefix("data:image/png;base64,")
        .ok_or("the texture is not an embedded PNG")?;
    let bytes = base64(data)?;
    let mut decoder = png::Decoder::new(std::io::Cursor::new(bytes));
    decoder.set_transformations(png::Transformations::normalize_to_color8() | png::Transformations::ALPHA);
    let mut reader = decoder.read_info().map_err(|e| e.to_string())?;
    let mut buf = vec![0; reader.output_buffer_size().ok_or("texture too big")?];
    let info = reader.next_frame(&mut buf).map_err(|e| e.to_string())?;
    let (width, height) = (info.width as usize, info.height as usize);
    let rgba = match info.color_type {
        png::ColorType::Rgba => buf[..width * height * 4].to_vec(),
        png::ColorType::GrayscaleAlpha => buf[..width * height * 2]
            .chunks(2)
            .flat_map(|g| [g[0], g[0], g[0], g[1]])
            .collect(),
        other => return Err(format!("texture colours {other:?}")),
    };
    Ok(Texture { width, height, rgba })
}

fn write_png(path: &Path, rgba: &[u8]) -> crate::Result {
    let file = std::fs::File::create(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut encoder = png::Encoder::new(std::io::BufWriter::new(file), SIZE.0 as u32, SIZE.1 as u32);
    encoder.set_color(png::ColorType::Rgba);
    encoder.set_depth(png::BitDepth::Eight);
    let mut writer = encoder.write_header().map_err(|e| format!("{}: {e}", path.display()))?;
    writer
        .write_image_data(rgba)
        .map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(())
}

fn base64(text: &str) -> Result<Vec<u8>, String> {
    let value = |c: u8| match c {
        b'A'..=b'Z' => Some(c - b'A'),
        b'a'..=b'z' => Some(c - b'a' + 26),
        b'0'..=b'9' => Some(c - b'0' + 52),
        b'+' => Some(62),
        b'/' => Some(63),
        _ => None,
    };
    let digits: Vec<u8> = text
        .bytes()
        .filter(|c| *c != b'=' && !c.is_ascii_whitespace())
        .map(|c| value(c).ok_or("bad base64"))
        .collect::<Result<_, _>>()?;
    let mut out = Vec::with_capacity(digits.len() * 3 / 4);
    for chunk in digits.chunks(4) {
        let n = chunk.iter().fold(0u32, |acc, d| acc << 6 | u32::from(*d)) << (6 * (4 - chunk.len()));
        out.extend_from_slice(&n.to_be_bytes()[1..chunk.len()]);
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decodes_base64() {
        assert_eq!(base64("aGVsbG8=").unwrap(), b"hello");
        assert_eq!(base64("aGk").unwrap(), b"hi");
    }

    #[test]
    fn the_front_view_faces_the_viewer() {
        // The model's front (+z) comes towards the viewer, its top up.
        assert!(view([0.0, 0.0, 1.0], 35.0)[2] > 0.0);
        assert!(view([0.0, 1.0, 0.0], 35.0)[1] > 0.0);
    }
}
